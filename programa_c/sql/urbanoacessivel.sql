-- DDL ---------------------------------------------------------
CREATE TABLE TB_VEICULO (
    ID_VEICULO      INT AUTO_INCREMENT PRIMARY KEY,
    PLACA           VARCHAR(8)  NOT NULL UNIQUE,
    PREFIXO_IOT     VARCHAR(12) NOT NULL UNIQUE,
    MODELO          VARCHAR(50) NOT NULL,
    ANO_FABRICACAO  INT         NOT NULL,
    STATUS_ELEVADOR VARCHAR(20) DEFAULT 'OPERACIONAL',
    STATUS_RAMPA    VARCHAR(20) DEFAULT 'OPERACIONAL',
    DATA_CADASTRO   TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
    CHECK (STATUS_ELEVADOR IN ('OPERACIONAL','ALERTA','QUEBRADO')),
    CHECK (STATUS_RAMPA    IN ('OPERACIONAL','ALERTA','QUEBRADO'))
);

CREATE TABLE TB_MECANICO (
    ID_MECANICO   INT AUTO_INCREMENT PRIMARY KEY,
    NOME          VARCHAR(100) NOT NULL,
    CPF           VARCHAR(14)  NOT NULL UNIQUE,
    ESPECIALIDADE VARCHAR(50)  NOT NULL
);

-- ID_MECANICO aceita NULL: a OS aberta automaticamente pelo sensor IoT
-- ainda nao tem responsavel; o gestor o atribui na triagem.
CREATE TABLE TB_ORDEM_SERVICO (
    ID_OS           INT AUTO_INCREMENT PRIMARY KEY,
    ID_VEICULO      INT          NOT NULL,
    ID_MECANICO     INT          NULL,
    TIPO_OS         VARCHAR(12)  NOT NULL DEFAULT 'CORRETIVA',
    DESCRICAO_FALHA TEXT         NOT NULL,
    DATA_ABERTURA   DATETIME     NOT NULL,
    DATA_AGENDADA   DATETIME     NULL,
    DATA_CONCLUSAO  DATETIME     NULL,
    STATUS_OS       VARCHAR(20)  DEFAULT 'EM_ABERTO',
    CHECK (TIPO_OS   IN ('CORRETIVA','PREVENTIVA')),
    CHECK (STATUS_OS IN ('EM_ABERTO','AGENDADA','CONCLUIDA')),
    FOREIGN KEY (ID_VEICULO)  REFERENCES TB_VEICULO(ID_VEICULO),
    FOREIGN KEY (ID_MECANICO) REFERENCES TB_MECANICO(ID_MECANICO)
);

CREATE INDEX IX_OS_STATUS ON TB_ORDEM_SERVICO (STATUS_OS, DATA_ABERTURA);

