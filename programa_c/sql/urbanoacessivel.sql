-- Consulta 1: ordens em aberto com veiculo e mecanico (INNER JOIN)
SELECT os.ID_OS, v.PLACA, v.MODELO, m.NOME AS MECANICO_RESPONSAVEL,
       os.DESCRICAO_FALHA, os.STATUS_OS, os.DATA_ABERTURA
FROM TB_ORDEM_SERVICO os
INNER JOIN TB_VEICULO  v ON os.ID_VEICULO  = v.ID_VEICULO
INNER JOIN TB_MECANICO m ON os.ID_MECANICO = m.ID_MECANICO
WHERE os.STATUS_OS = 'EM_ABERTO'
ORDER BY os.DATA_ABERTURA DESC;

-- Consulta 2 (RF05): historico completo de uma placa, inclusive OS sem mecanico (LEFT JOIN)
SELECT os.ID_OS, os.TIPO_OS, os.STATUS_OS, os.DATA_ABERTURA, os.DATA_CONCLUSAO,
       COALESCE(m.NOME, '(nao atribuido)') AS MECANICO
FROM TB_ORDEM_SERVICO os
INNER JOIN TB_VEICULO v ON os.ID_VEICULO = v.ID_VEICULO
LEFT  JOIN TB_MECANICO m ON os.ID_MECANICO = m.ID_MECANICO
WHERE v.PLACA = 'BRA2E19'
ORDER BY os.DATA_ABERTURA;

-- Consulta 3 (RF06): percentual da frota com acessibilidade 100% ativa
SELECT COUNT(*) AS TOTAL,
       SUM(CASE WHEN STATUS_ELEVADOR = 'OPERACIONAL' AND STATUS_RAMPA = 'OPERACIONAL'
                THEN 1 ELSE 0 END) AS ATIVOS,
       ROUND(100.0 * SUM(CASE WHEN STATUS_ELEVADOR = 'OPERACIONAL' AND STATUS_RAMPA = 'OPERACIONAL'
                              THEN 1 ELSE 0 END) / COUNT(*), 1) AS PERCENTUAL_ATIVO
FROM TB_VEICULO;

-- Fechamento de OS (transacao: OS concluida e veiculo liberado juntos)
START TRANSACTION;
UPDATE TB_ORDEM_SERVICO SET STATUS_OS = 'CONCLUIDA', DATA_CONCLUSAO = NOW() WHERE ID_OS = 1;
UPDATE TB_VEICULO SET STATUS_ELEVADOR = 'OPERACIONAL' WHERE ID_VEICULO = 1;
COMMIT;
